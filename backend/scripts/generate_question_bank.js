// Generate choice mapping
function generateChoiceMapping(intentType, choices) {
  const mapping = {};
  
  choices.forEach(choice => {
    if (intentType === 'severity') {
      if (choice === 'ใช่') {
        mapping[choice] = {
          severity: "moderate",
          confidence_boost: 0.10,
          follow_up: []
        };
      } else if (choice === 'ไม่') {
        mapping[choice] = {
          severity: "mild",
          confidence_boost: 0.05,
          follow_up: []
        };
      } else {
        mapping[choice] = {
          confidence_boost: 0.02,
          follow_up: []
        };
      }
    } else if (intentType === 'time_course') {
      if (choice === 'น้อยกว่า 3 วัน') {
        mapping[choice] = {
          time_course: "acute",
          confidence_boost: 0.08,
          follow_up: []
        };
      } else if (choice === '3-7 วัน') {
        mapping[choice] = {
          time_course: "subacute",
          confidence_boost: 0.08,
          follow_up: []
        };
      } else if (choice === '1-2 สัปดาห์') {
        mapping[choice] = {
          time_course: "subacute",
          confidence_boost: 0.06,
          follow_up: []
        };
      } else if (choice === 'มากกว่า 2 สัปดาห์' || choice === 'เป็นๆ หายๆ') {
        mapping[choice] = {
          time_course: "recurrent",
          confidence_boost: 0.06,
          follow_up: []
        };
      } else {
        mapping[choice] = {
          confidence_boost: 0.02,
          follow_up: []
        };
      }
    } else if (intentType === 'red_flag_exclusion') {
      if (choice === 'ใช่') {
        mapping[choice] = {
          red_flag_hint: true,
          confidence_boost: 0.15,
          emergency: true,
          follow_up: []
        };
      } else {
        mapping[choice] = {
          red_flag_hint: false,
          confidence_boost: 0.10,
          follow_up: []
        };
      }
    } else {
      // Default mapping for other intent types
      if (choice === 'ใช่') {
        mapping[choice] = {
          confidence_boost: 0.05,
          follow_up: []
        };
      } else if (choice === 'ไม่') {
        mapping[choice] = {
          confidence_boost: 0.03,
          follow_up: []
        };
      } else {
        mapping[choice] = {
          confidence_boost: 0.01,
          follow_up: []
        };
      }
    }
  });
  
  return mapping;
}

// Generate questions for a symptom group
function generateQuestionsForGroup(symptomGroup) {
  const questions = [];
  let questionIndex = 1;
  
  // Generate questions for each intent type
  Object.keys(INTENT_TYPE_CONFIG).forEach(intentType => {
    const config = INTENT_TYPE_CONFIG[intentType];
    const templates = QUESTION_TEMPLATES[intentType]?.[symptomGroup.id] || [];
    
    // Determine how many questions of this type to generate
    let count = 0;
    if (intentType === 'severity') count = 8;
    else if (intentType === 'time_course') count = 8;
    else if (intentType === 'red_flag_exclusion') count = 6;
    else if (intentType === 'body_part_detail') count = 4;
    else if (intentType === 'associated_symptom') count = 6;
    else if (intentType === 'trigger') count = 4;
    else if (intentType === 'functional_impact') count = 4;
    else if (intentType === 'relieving_factor') count = 2;
    else if (intentType === 'risk_factor') count = 2;
    
    // Generate questions
    // If no templates available, use generic templates
    const availableTemplates = templates.length > 0 ? templates : getGenericTemplates(intentType, symptomGroup.id);
    
    for (let i = 0; i < count && i < availableTemplates.length; i++) {
      const questionText = availableTemplates[i];
      const confidenceWeight = config.confidence_weight_range[0] + 
        (Math.random() * (config.confidence_weight_range[1] - config.confidence_weight_range[0]));
      
      const question = {
        question_id: `${symptomGroup.id.toUpperCase()}_${intentType.toUpperCase()}_${String(questionIndex).padStart(3, '0')}`,
        question_text_th: questionText,
        question_text_en: "", // Can be added later
        symptom_group: symptomGroup.id,
        intent_type: intentType,
        confidence_weight: Math.round(confidenceWeight * 100) / 100,
        when_to_ask: config.when_to_ask,
        exclude_if: getExcludeConditions(intentType),
        requires_body_part: intentType === 'body_part_detail',
        body_part_specific: [],
        severity_filter: null,
        time_course_filter: null,
        choices: config.choices,
        choice_mapping: generateChoiceMapping(intentType, config.choices),
        follow_up_questions: [],
        skip_if_answered: [],
        priority: config.priority
      };
      
      questions.push(question);
      questionIndex++;
    }
  });
  
  return questions;
}

