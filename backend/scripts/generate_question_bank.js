// Get exclude conditions for intent type
function getExcludeConditions(intentType) {
  const excludeConditions = [];
  
  if (intentType === 'red_flag_exclusion') {
    excludeConditions.push('emergency_detected');
  } else if (intentType === 'severity') {
    excludeConditions.push('emergency_detected', 'severe_confirmed');
  } else if (intentType === 'body_part_detail') {
    excludeConditions.push('body_part_unknown');
  }
  
  return excludeConditions;
}

