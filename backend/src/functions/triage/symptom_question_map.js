/**
 * Find matching symptom keywords in text
 * Returns array of matching keywords (longest, most specific match first)
 * CRITICAL: Check longer keywords first to avoid substring matches
 * CRITICAL: Trim whitespace and normalize for better matching
 * CRITICAL: Also check for partial matches (e.g., "ปวดหลัง" should match even if text is "ปวดหลังมาก")
 */
export function findMatchingKeywords(symptomText) {
  // Normalize: trim whitespace, lowercase, remove extra spaces
  const normalized = symptomText.trim().toLowerCase().replace(/\s+/g, ' ');
  const matches = [];
  
  // Sort keywords by length (longest first) to prioritize specific matches
  // e.g., "ไข้สูง" should match before "ไข้"
  const sortedKeywords = Object.keys(SYMPTOM_QUESTION_MAP).sort((a, b) => b.length - a.length);
  
  // Track which parts of the text have been matched to avoid duplicate matches
  const matchedRanges = [];
  
  for (const keyword of sortedKeywords) {
    const keywordLower = keyword.toLowerCase();
    
    // Check for exact match or substring match
    // CRITICAL: "ปวดหลัง" should match in "ปวดหลังมาก" or "ปวดหลัง 2 วัน"
    const keywordIndex = normalized.indexOf(keywordLower);
    
    if (keywordIndex !== -1) {
      // Check if this range overlaps with an existing match
      const keywordEnd = keywordIndex + keywordLower.length;
      const overlaps = matchedRanges.some(([start, end]) => 
        (keywordIndex >= start && keywordIndex < end) ||
        (keywordEnd > start && keywordEnd <= end) ||
        (keywordIndex <= start && keywordEnd >= end)
      );
      
      if (!overlaps) {
        matches.push(keyword);
        matchedRanges.push([keywordIndex, keywordEnd]);
      }
    }
  }
  
  return matches;
}

/**
 * Get symptom-specific first question (Red-Flag Focused)
 * CRITICAL: If multiple keywords match, prioritize the LONGEST/MOST SPECIFIC match
 * This ensures "ไข้สูง" matches "ไข้สูง" (4 chars) before "ไข้" (2 chars)
 * 
 * First-Gate Triage: Red flags detected → Emergency flow immediately
 * No red flags → Proceed to hypothesis, medication options, follow-up
 */
export function getSymptomSpecificQuestion(symptomText) {
  const matches = findMatchingKeywords(symptomText);
  
  if (matches.length === 0) {
    return null; // No match
  }
  
  // CRITICAL: Always use the FIRST match (longest/most specific)
  // matches are already sorted by length (longest first) from findMatchingKeywords
  // So matches[0] is the most specific match
  const selectedKeyword = matches[0];
  const question = SYMPTOM_QUESTION_MAP[selectedKeyword];
  
  console.log(`[SYMPTOM-MAP] Input: "${symptomText}", Matches: [${matches.join(', ')}], Selected: "${selectedKeyword}", Question: "${question}"`);
  
  return question;
}
